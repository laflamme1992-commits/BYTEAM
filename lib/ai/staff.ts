export type StaffRole = (typeof staffRoles)[number]["id"];
export type ChatMessage = { role: "user" | "assistant"; content: string };
export type TaskProposal = {
  type: "create_task";
  title: string;
  assignee: string;
  deadline: string;
  status: "todo";
};
export type StaffRequest = {
  role: StaffRole;
  messages: ChatMessage[];
  context: string;
};
export function isStaffRole(value: unknown): value is StaffRole {
  return staffRoles.some((role) => role.id === value);
}
export function parseStaffRequest(payload: unknown): StaffRequest | null {
  if (!payload || typeof payload !== "object") return null;
  const p = payload as Record<string, unknown>;
  const role = p.role ?? "manager";
  if (
    !isStaffRole(role) ||
    !Array.isArray(p.messages) ||
    !p.messages.length ||
    p.messages.length > 20
  )
    return null;
  if (
    p.context !== undefined &&
    (typeof p.context !== "string" || p.context.length > 3000)
  )
    return null;
  const messages: ChatMessage[] = [];
  for (const m of p.messages) {
    if (
      !m ||
      typeof m !== "object" ||
      !["user", "assistant"].includes(m.role) ||
      typeof m.content !== "string" ||
      !m.content.trim() ||
      m.content.length > 4000
    )
      return null;
    messages.push({ role: m.role, content: m.content });
  }
  if (messages[messages.length - 1].role !== "user") return null;
  return {
    role,
    messages,
    context: typeof p.context === "string" ? p.context : "",
  };
}
export function parseTaskProposal(
  value: unknown,
  role: StaffRole,
): TaskProposal | null {
  if (
    !["manager", "coach"].includes(role) ||
    !value ||
    typeof value !== "object"
  )
    return null;
  const p = value as Record<string, unknown>;
  if (
    p.type !== "create_task" ||
    typeof p.title !== "string" ||
    !p.title.trim() ||
    p.title.length > 200
  )
    return null;
  const deadline = typeof p.deadline === "string" ? p.deadline : "";
  if (deadline) {
    const date = new Date(deadline + "T12:00:00Z");
    if (
      !/^\d{4}-\d{2}-\d{2}$/.test(deadline) ||
      Number.isNaN(date.getTime()) ||
      date.toISOString().slice(0, 10) !== deadline
    )
      return null;
  }
  return {
    type: "create_task",
    title: p.title.trim(),
    assignee: typeof p.assignee === "string" ? p.assignee.slice(0, 100) : "",
    deadline,
    status: "todo",
  };
}
